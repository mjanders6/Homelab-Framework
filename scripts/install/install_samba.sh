#!/usr/bin/env bash

##############################################################################
#
# Home Lab Setup — Install Samba Packages
#
##############################################################################

set -e

echo "Installing Samba packages..."

sudo apt update

sudo apt install -y \
    samba \
    samba-common-bin \
    cifs-utils

##############################################################################
# Enable Samba Services
##############################################################################

sudo systemctl enable smbd
sudo systemctl restart smbd

##############################################################################
# Firewall Rules
##############################################################################

sudo ufw allow samba || true

##############################################################################
# Status
##############################################################################

echo ""
echo "Samba packages installed successfully."